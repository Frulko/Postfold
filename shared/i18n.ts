export function translate(locale: Locale, key: string, ...values: (string | number)[]) {
  const message = locale === 'en' ? english[key] ?? key : french[key] ?? key
  return message.replace(/\{(\d+)\}/g, (match, index) => String(values[Number(index)] ?? match))
}
